#!/usr/bin/env python3
"""Regenerate the colored example images under docs/.

elfcheck colors each severity tag by a pure function of severity (HIGH=red,
MED=yellow, LOW=cyan, INFO=grey) and the entropy packer flag [high] in the same
red, so these SVGs faithfully reproduce real `elfcheck --triage` / `--entropy`
output from the plain text alone -- no screenshot needed. Deliberately
understated (a flat dark panel, no window chrome). Run from the repo root:
  python3 docs/gen-examples.py
"""
import html

SEV = {
    "[HIGH]": ("#e06c75", True),
    "[MED]":  ("#e5c07b", False),
    "[LOW]":  ("#56b6c2", False),
    "[INFO]": ("#7f848e", False),
}
TEXT, DIM = "#abb2bf", "#5c6370"
BG, BORDER = "#282c34", "#21252b"
FONT = "ui-monospace,'SF Mono',Menlo,Consolas,'DejaVu Sans Mono',monospace"
FS, LH, PAD_X, PAD_T, PAD_B = 14, 22, 18, 16, 14
CW = FS * 0.6
MINCOLS = 50  # shared minimum width so sibling examples line up


HIMARK = "  [high]"  # entropy packer flag, colored like HIGH (bold red)


def spans(line):
    if line.startswith("$ "):
        return [("$", DIM, False), (line[1:], TEXT, False)]
    if line.endswith(HIMARK):
        col, _ = SEV["[HIGH]"]
        return [(line[:-len(HIMARK)], TEXT, False), (HIMARK, col, True)]
    stripped = line.lstrip()
    for tag, (col, bold) in SEV.items():
        if stripped.startswith(tag):
            return [(line[:11], col, bold), (line[11:], TEXT, False)]
    return [(line, TEXT, False)]


def render(lines, out, label, cols):
    W = int(PAD_X * 2 + cols * CW)
    H = int(PAD_T + len(lines) * LH + PAD_B)
    s = ['<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" '
         'viewBox="0 0 %d %d" role="img" aria-label="%s">'
         % (W, H, W, H, html.escape(label)),
         '<!-- Generated by docs/gen-examples.py from real elfcheck '
         'output; tags colored HIGH=red MED=yellow LOW=cyan INFO=grey. -->',
         '<rect x="0.5" y="0.5" width="%d" height="%d" rx="7" fill="%s" stroke="%s"/>'
         % (W - 1, H - 1, BG, BORDER)]
    y = PAD_T + FS
    for line in lines:
        if line:
            runs = "".join(
                '<tspan fill="%s"%s>%s</tspan>'
                % (f, ' font-weight="600"' if b else "", html.escape(t))
                for t, f, b in spans(line))
            s.append('<text x="%d" y="%d" xml:space="preserve" font-family="%s" '
                     'font-size="%d">%s</text>' % (PAD_X, y, FONT, FS, runs))
        y += LH
    s.append("</svg>\n")
    open(out, "w").write("\n".join(s))
    print("wrote", out, "(%dx%d)" % (W, H))


clean = [
    "$ elfcheck --triage ./elfcheck",
    "Triage:",
    "  [LOW]    no RELRO (GOT is writable)",
    "  [LOW]    no PIE (fixed load address)",
    "  [LOW]    no stack canary",
    "  [LOW]    CET not fully enabled (IBT/SHSTK)",
    "  Summary: 0 high, 0 medium, 4 low, 0 info",
    "",
    "$ echo $?",
    "0",
]
vuln = [
    "$ elfcheck --triage ./vuln",
    "Triage:",
    "  [HIGH]   executable stack (PT_GNU_STACK is RWX)",
    "  [LOW]    partial RELRO (GOT not fully protected)",
    "  [LOW]    no PIE (fixed load address)",
    "  [LOW]    no stack canary",
    "  [LOW]    CET not fully enabled (IBT/SHSTK)",
    "  Summary: 1 high, 0 medium, 4 low, 0 info",
    "",
    "$ echo $?",
    "2",
]

entropy = [
    "$ elfcheck --entropy ./packed",
    "Entropy:",
    "  5.961 bits/byte  .text",
    "  5.399 bits/byte  .rodata",
    "  7.991 bits/byte  .packed  [high]",
    "  3.597 bits/byte  .shstrtab",
]
suspicious = [
    "$ elfcheck --triage ./suspicious",
    "Triage:",
    "  [MED]    high-entropy executable section (possibly packed/encrypted)",
    "  [LOW]    imports command/process execution (system/exec*)",
    "  [INFO]   imports network functions (socket/connect/...)",
    "  Summary: 0 high, 1 medium, 1 low, 1 info",
    "",
    "$ echo $?",
    "2",
]

# One shared width across every panel so the images line up side by side.
ALL = (clean, vuln, entropy, suspicious)
COLS = max(MINCOLS, max(len(l) for ex in ALL for l in ex))

render(clean, "docs/triage-clean.svg",
       "elfcheck triage of a clean binary: four cyan LOW findings, exits 0", COLS)
render(vuln, "docs/triage-vuln.svg",
       "elfcheck triage of a vulnerable binary: a red HIGH finding over cyan LOW findings, exits 2", COLS)
render(suspicious, "docs/triage-suspicious.svg",
       "elfcheck triage of a suspicious binary: a yellow MED, a cyan LOW and a grey INFO finding, exits 2", COLS)
render(entropy, "docs/entropy-packed.svg",
       "elfcheck entropy report: a high-entropy executable section flagged [high] in red", COLS)
